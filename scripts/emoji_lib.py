def code(name):
    """返回 (ISO2代码, (色1, 色2))；国别题材用。"""
    e = COUNTRIES.get(name)
    if e is None:
        return None
    return e


def emoji(name):
    """返回 (emoji/字母, 行业色)；公司/品牌用。fallback: 名称首字母 + 灰。"""
    e = COMPANIES.get(name)
    if e is not None:
        return e
    # 未收录：取中文首字（first_two 对纯拉丁品牌名回退到前两个字母），
    # 不再用 name[:1].upper() 制造单个英文字母（2026-09-07 去英文）
    letter = first_two(name)
    return (letter, 'industrial', '#94a3b8')


def tint_for_country(name):
    """国别用：返回 (色1, 色2) 边框色。"""
    e = code(name)
    if e is None:
        return ('#888888', '#bbbbbb')
    return e[1]


def color_for(name):
    """总入口：返回 (图标字符串, 边框主色, 边框次色)，用于柱子末端徽章。"""
    e = code(name)
    if e is not None:
        return (e[0], e[1][0], e[1][1])
    e = emoji(name)
    return (e[0], e[1], INDUSTRY_TINT.get(e[1], INDUSTRY_TINT['industrial'])[0])


def first_two(name):
    """国别 fallback 文字代号：取名字前两个字符（如「广东(含深穗) → 广东」首字）或首字母。"""
    s = ''.join(c for c in name if '\u4e00' <= c <= '\u9fff')[:1]
    if s:
        return s
    return name[:2].upper() if name else '?'


